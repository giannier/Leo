/**
 * The icon set.
 *
 * Inlined rather than pulled from a package: the panel needs a dozen glyphs,
 * and a dependency for that is a dependency to keep updated and to ship. They
 * share one visual language - 24×24 grid, 1.75 stroke, round caps - because
 * mixing stroke weights is the difference between a product that looks made
 * and one that looks assembled.
 *
 * Never emoji. An emoji renders differently on every phone, cannot inherit
 * colour, and is announced by screen readers as its own name.
 */

type IconProps = {
  className?: string;
  /** Omit for decorative icons that sit next to a text label. */
  title?: string;
};

function Svg({ className, title, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className ?? "size-5"}
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}

